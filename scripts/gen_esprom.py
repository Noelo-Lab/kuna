#!/usr/bin/env python3
"""Generate the Espressif mask-ROM symbol tables kuna's `esprom` option reads.

Sources (both Apache-2.0):
  ESP-IDF            components/esp_rom/<chip>/ld/*.ld        (esp32, esp32s2,
                     esp32s3, esp32c2, esp32c3, esp32c6, esp32h2)
  ESP8266_RTOS_SDK   components/esp8266/ld/esp8266.rom.ld     (esp8266)

Usage:
  git clone --depth 1 -b v5.5.6 https://github.com/espressif/esp-idf
  git clone --depth 1 -b v3.4   https://github.com/espressif/ESP8266_RTOS_SDK
  scripts/gen_esprom.py --idf esp-idf --idf-tag v5.5.6 \
      --rtos8266 ESP8266_RTOS_SDK --rtos8266-tag v3.4

Each `name = 0xADDR;` / `PROVIDE(name = 0xADDR);` assignment becomes one line
`<hex address> <F|D> <name>` in
decompiler/crates/kuna-analysis/src/loader/firmware/esprom/<chip>.txt, sorted
by address. `F` is a function: an address inside the chip's mask-ROM code
range that the script does not list under a `Data` heading. The chip's main
`<chip>.rom.ld` is read first; the first name an address gets and the first
address a name gets are kept, so one address has one name and a name that a
later ROM revision moved keeps its original address. An assignment outside
the chips' address space is a constant, not a symbol, and is dropped.
"""

import argparse
import pathlib
import re

# Mask-ROM code range per chip: SOC_IROM_MASK_LOW/HIGH of
# components/soc/<chip>/include/soc/soc.h; the ESP8266 ROM is 64 KiB at
# 0x40000000 (ESP8266 Technical Reference, memory map).
ROM_CODE = {
    "esp32": (0x40000000, 0x40070000),
    "esp32s2": (0x40000000, 0x40020000),
    "esp32s3": (0x40000000, 0x40060000),
    "esp32c2": (0x40000000, 0x40090000),
    "esp32c3": (0x40000000, 0x40060000),
    "esp32c6": (0x40000000, 0x40050000),
    "esp32h2": (0x40000000, 0x40020000),
    "esp8266": (0x40000000, 0x40010000),
}
IDF_CHIPS = [c for c in ROM_CODE if c != "esp8266"]
# Every chip's memory lies in this range; an assignment outside it is a
# constant the script defines, not an address.
ADDRESS_SPACE = (0x3C000000, 0x62000000)

ASSIGN = re.compile(
    r"^\s*(?:PROVIDE\s*\(\s*)?([A-Za-z_][A-Za-z0-9_$.]*)\s*=\s*(0x[0-9a-fA-F]+)\s*\)?\s*;"
)
HEADING = re.compile(r"/\*\s*(Functions|Data)\b")


def symbols(chip, files):
    lo, hi = ROM_CODE[chip]
    by_addr, names = {}, set()
    for path in files:
        data = False
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            heading = HEADING.search(line)
            if heading:
                data = heading.group(1) == "Data"
            m = ASSIGN.match(re.sub(r"/\*.*?\*/", "", line))
            if not m:
                continue
            name, addr = m.group(1), int(m.group(2), 16)
            if addr in by_addr or name in names:
                continue
            if not ADDRESS_SPACE[0] <= addr < ADDRESS_SPACE[1]:
                continue
            names.add(name)
            by_addr[addr] = ("F" if lo <= addr < hi and not data else "D", name)
    return sorted(by_addr.items())


def write(out, chip, source, rows):
    lines = [
        f"# {chip} mask-ROM symbols: <hex address> <F function | D data> <name>",
        f"# Generated by scripts/gen_esprom.py from {source} (Apache-2.0).",
    ]
    lines += [f"{addr:08x} {kind} {name}" for addr, (kind, name) in rows]
    (out / f"{chip}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    funcs = sum(1 for _, (kind, _) in rows if kind == "F")
    print(f"{chip}: {funcs} functions, {len(rows) - funcs} data")


def main():
    repo = pathlib.Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--idf", type=pathlib.Path, required=True)
    ap.add_argument("--idf-tag", required=True)
    ap.add_argument("--rtos8266", type=pathlib.Path, required=True)
    ap.add_argument("--rtos8266-tag", required=True)
    ap.add_argument(
        "--out",
        type=pathlib.Path,
        default=repo / "decompiler/crates/kuna-analysis/src/loader/firmware/esprom",
    )
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    for chip in IDF_CHIPS:
        ld = args.idf / "components/esp_rom" / chip / "ld"
        main_ld = ld / f"{chip}.rom.ld"
        files = [main_ld] + sorted(p for p in ld.glob("*.ld") if p != main_ld)
        source = f"ESP-IDF {args.idf_tag} components/esp_rom/{chip}/ld/*.ld"
        write(args.out, chip, source, symbols(chip, files))
    rom = args.rtos8266 / "components/esp8266/ld/esp8266.rom.ld"
    source = f"ESP8266_RTOS_SDK {args.rtos8266_tag} components/esp8266/ld/esp8266.rom.ld"
    write(args.out, "esp8266", source, symbols("esp8266", [rom]))


if __name__ == "__main__":
    main()
