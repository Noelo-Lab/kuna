#!/usr/bin/env python3
"""Generate the Android JNI declarations consumed by the native loader.

    python3 scripts/gen_android_jni.py <ndk>/toolchains/llvm/prebuilt/<host>/sysroot/usr/include/jni.h

The C branch of the public NDK header defines the native ABI used by both C and
C++. The ABI preambles supply jlong's underlying integer and va_list's argument
type (an array parameter decays to a pointer on x86_64).
"""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import tempfile

NDK_VERSION = "r30"
HEADER_SHA256 = "5df9074457c041b372f2c68ff646d6e8600cd673a223885e8df21c44c94ec667"
OUT = Path(__file__).resolve().parents[1] / "decompiler/crates/kuna-analysis/data/android-jni"

INTS = {
    "uint8_t": "unsigned char",
    "int8_t": "signed char",
    "uint16_t": "unsigned short",
    "int16_t": "short",
    "int32_t": "int",
    "int64_t": "jni_int64",
}


def declarations(source: str):
    """Emit preprocessed declarations with a single record member per line."""
    depth = 0
    start = 0
    for index, char in enumerate(source):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        elif char == ";" and depth == 0:
            decl = " ".join(source[start:index + 1].split())
            start = index + 1
            if "{" in decl:
                head, rest = decl.split("{", 1)
                fields, tail = rest.rsplit("}", 1)
                separator = "," if "enum " in head else ";"
                members = [f"    {field.strip()}{separator}" for field in fields.split(separator) if field.strip()]
                yield "\n".join([head + "{", *members, "}" + tail])
            else:
                yield decl
    if depth or source[start:].strip():
        raise ValueError("expected complete C declarations")


def generate(header: Path, clang: Path) -> str:
    raw = header.read_bytes()
    if hashlib.sha256(raw).hexdigest() != HEADER_SHA256:
        raise ValueError(f"{header} does not match the pinned Android NDK {NDK_VERSION} jni.h")
    # Only JNI declarations enter the global type factory. Keep compiler-private
    # symbols from stdint.h and stdarg.h out of it.
    with tempfile.TemporaryDirectory() as tmp:
        includes = Path(tmp)
        (includes / "stdint.h").write_text("".join(f"#define {k} {v}\n" for k, v in INTS.items()))
        (includes / "stdarg.h").write_text("#define va_list jni_va_list_arg\n")
        source = subprocess.check_output(
            [clang, "-E", "-P", "-x", "c", "-nostdinc", "-I", tmp, "-"],
            input=f'#include "{header.resolve()}"\n', text=True,
        )
    source = re.sub(r'__attribute__\s*\(\s*\(\s*visibility\s*\(\s*"default"\s*\)\s*\)\s*\)', '', source)
    # C tags and typedefs share Kuna's type namespace. Use distinct tags for
    # enum typedefs and retain the public typedef spelling in all declarations.
    source = source.replace("typedef enum jobjectRefType", "typedef enum JNIReferenceType")
    output = [f"""/* Copyright (C) 2006 The Android Open Source Project. Apache-2.0.
 * Generated by scripts/gen_android_jni.py from Android NDK {NDK_VERSION} jni.h.
 * SHA-256 {HEADER_SHA256}
 */"""]
    for decl in declarations(source):
        if re.match(r"^jint JNI_|^void JNI_", decl):
            decl = "extern " + decl
        output.append(decl)
    return "\n\n".join(output) + "\n"


def verify_abis(header: Path, clang: Path, rendered: str) -> None:
    """Compare every slot offset and every lowered function ABI with NDK Clang."""
    probe = []
    names = []
    for table in ("JNINativeInterface", "JNIInvokeInterface"):
        body = rendered.split(f"struct {table} {{", 1)[1].split("};", 1)[0]
        fields = body.strip().splitlines()
        probe.append(f'_Static_assert(sizeof(struct {table}) == {len(fields)} * sizeof(void *), "{table}");')
        for index, field in enumerate(fields):
            method = re.search(r"\(\*(\w+)\)", field)
            if method:
                name = method[1]
                names.append(name)
                probe.append(f"extern __typeof__(*(((struct {table} *)0)->{name})) abi_{name};")
            else:
                name = field.strip().split()[-1].removesuffix(";")
            probe.append(f'_Static_assert(__builtin_offsetof(struct {table}, {name}) == {index} * sizeof(void *), "{name}");')
    for name in re.findall(r"^extern .+? (JNI_\w+)\(", rendered, re.M):
        names.append(name)
        probe.append(f"extern __typeof__({name}) abi_{name};")
    probe.append("void *const all_methods[] = {" + ", ".join(f"(void *)&abi_{name}" for name in names) + "};")
    targets = {
        "arm64": "aarch64-linux-android24", "arm": "armv7a-linux-androideabi24",
        "x86_64": "x86_64-linux-android24", "x86": "i686-linux-android24",
    }
    for abi, target in targets.items():
        args = [clang, f"--target={target}", "-x", "c", "-Werror", "-S", "-emit-llvm", "-o", "-", "-"]
        preamble = (OUT / f"va-{abi}.h").read_text()
        actual = []
        for source in (f'#include "{header.resolve()}"', preamble + rendered):
            ir = subprocess.check_output(args, input="\n".join([source, *probe]), text=True)
            actual.append(sorted(line for line in ir.splitlines() if line.startswith("declare ")))
        if len(actual[0]) != len(names) or actual[0] != actual[1]:
            raise ValueError(f"JNI function prototypes differ from the {abi} NDK ABI")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("header", type=Path)
    parser.add_argument("--clang", type=Path, help="NDK Clang; defaults to the toolchain containing jni.h")
    parser.add_argument("--check", action="store_true", help="compare with the committed declarations")
    args = parser.parse_args()
    output = OUT / "jni-types.h"
    clang = args.clang or args.header.resolve().parents[3] / "bin/clang"
    rendered = generate(args.header, clang)
    verify_abis(args.header, clang, rendered)
    if args.check:
        if output.read_text() != rendered:
            parser.exit(1, f"{output} is out of date\n")
    else:
        output.write_text(rendered)


if __name__ == "__main__":
    main()
