"""Decompiler-independent ground-truth index of a project.

For every class-file method it either records ground truth (source CFG, source
variable types, bytecode size) or an exclusion reason. The resulting scored set
is the SHARED denominator for every decompiler. Written to
``<dataset>/<project>/index.json.gz``; the default sample is derived from it.
"""

from __future__ import annotations

import gzip
import hashlib
import json
import os
import re
import sys
import zipfile
from collections import Counter, defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from . import projects as P
from .cfg import build_cfg, run_big_stack
from .classfile import ClassFile, parse_class
from .javasrc import index_source
from .jtypes import descriptor_to_java, method_vars, normalize, signature_to_java
from .mapping import import_map, is_scored_method, map_method, map_types, method_key

INDEX_VERSION = 5
# Machine-generated sources (ANTLR/JavaCC parsers, generated tables) are not
# hand-written ground truth; decided from the file HEADER only (first 3000 bytes).
GENERATED = re.compile(
    rb"\$ANTLR|Generated By:JavaCC|automatically generated|AUTO-GENERATED|DO NOT EDIT|"
    rb"generated by (?:the )?protoc|@javax\.annotation\.Generated|@jakarta\.annotation\.Generated|@Generated\(")
STRATA = [(1, 16), (17, 64), (65, 256), (257, 1024), (1025, 10**9)]

_ZIP: dict[str, zipfile.ZipFile] = {}


def _zip(path: str) -> zipfile.ZipFile:
    z = _ZIP.get(path)
    if z is None:
        z = _ZIP[path] = zipfile.ZipFile(path)
    return z


def load_classes(jar: str, names: list[str]) -> dict[str, ClassFile]:
    z = _zip(jar)
    out = {}
    for n in names:
        cf = parse_class(z.read(n + ".class"))
        out[cf.name] = cf
    return out


def source_path_of(cf: ClassFile) -> str:
    pkg = cf.name.rsplit("/", 1)[0] if "/" in cf.name else ""
    sf = cf.source_file or (cf.name.rsplit("/", 1)[-1].split("$")[0] + ".java")
    return f"{pkg}/{sf}" if pkg else sf


def stratum(code_len: int) -> int:
    for i, (lo, hi) in enumerate(STRATA):
        if lo <= code_len <= hi:
            return i
    return len(STRATA) - 1


def _var_gt(m, md, vars_):
    """Fill ``var`` locals from LVTT/LVT (by name + order); returns list of dicts."""
    lvt = m.code.locals if m.code else []
    by_name: dict[str, list] = defaultdict(list)
    for lv in lvt:
        by_name[lv.name].append(lv)
    seen: Counter = Counter()
    out = []
    for v in vars_:
        rec = {"role": v.role, "index": v.index, "name": v.name, "type": v.type_text, "src": "source"}
        if v.role == "local":
            k = seen[v.name]
            seen[v.name] += 1
            if v.is_var:
                cands = by_name.get(v.name, [])
                if k < len(cands):
                    lv = cands[k]
                    rec["type"] = signature_to_java(lv.signature) if lv.signature else descriptor_to_java(lv.descriptor)
                    rec["src"] = "lvtt" if lv.signature else "lvt"
                else:
                    rec["src"] = "unscorable-var"
        elif v.is_var:
            rec["src"] = "unscorable-var"
        out.append(rec)
    return out


def _index_unit(args):
    jar, src_root, rel, class_names = args
    return run_big_stack(_index_unit_inner, jar, src_root, rel, class_names)


def _index_unit_inner(jar, src_root, rel, class_names):
    classes = load_classes(jar, class_names)
    recs = []
    excl = []
    path = Path(src_root) / rel
    scored_methods = []
    for cf in classes.values():
        for m in cf.methods:
            ok, why = is_scored_method(m)
            if ok:
                scored_methods.append((cf, m))
            elif why != "no-code":
                excl.append((method_key(cf, m), why))
    if not path.exists():
        for cf, m in scored_methods:
            excl.append((method_key(cf, m), "class-not-in-sources"))
        return recs, excl
    raw = path.read_bytes()
    if GENERATED.search(raw[:3000]):
        for cf, m in scored_methods:
            excl.append((method_key(cf, m), "generated-source"))
        return recs, excl
    idx = index_source(raw)
    tmap = map_types(classes, [idx], use_lines=True)
    imports = import_map(idx)
    for cf, m in scored_methods:
        key = method_key(cf, m)
        t = tmap.get(cf.name)
        if t is None:
            excl.append((key, "type-not-mapped"))
            continue
        md, why = map_method(t, cf, m, use_lines=True, imports=imports)
        if md is None:
            excl.append((key, why))
            continue
        if md.has_error:
            excl.append((key, "source-parse-error"))
            continue
        cfg = build_cfg(md.body)
        vars_ = _var_gt(m, md, method_vars(md))
        top = cf.dotted.split("$")[0]
        recs.append({
            "key": key,
            "class": cf.dotted,
            "top": top,
            "name": m.name,
            "desc": m.descriptor,
            "file": rel,
            "span": [md.start_line, md.end_line],
            "code_len": len(m.code.code),
            "stratum": stratum(len(m.code.code)),
            "release": max(8, cf.major - 44),
            "has_lines": bool(m.code.lines),
            "has_lvt": bool(m.code.locals),
            "cfg": cfg.to_json(),
            "vars": vars_,
            "tparams": md.scope_type_params(),
            "kind": t.kind,
        })
    return recs, excl


def build_index(proj: P.Project, jobs: int = 16) -> dict:
    d = proj.dir
    jar = str(d / "classes.jar")
    names = [n[:-6] for n in zipfile.ZipFile(jar).namelist() if n.endswith(".class")]
    units: dict[str, list[str]] = defaultdict(list)
    z = zipfile.ZipFile(jar)
    for n in names:
        if n.endswith("package-info"):
            continue
        cf = parse_class(z.read(n + ".class"))
        units[source_path_of(cf)].append(n)
    tasks = [(jar, str(d / "sources"), rel, cls) for rel, cls in sorted(units.items())]
    recs: list[dict] = []
    excl: list[tuple[str, str]] = []
    with ProcessPoolExecutor(max_workers=jobs) as ex:
        for r, e in ex.map(_index_unit, tasks, chunksize=8):
            recs.extend(r)
            excl.extend(e)
    recs.sort(key=lambda r: r["key"])
    reasons = Counter(why for _, why in excl)
    index = {
        "version": INDEX_VERSION,
        "project": proj.name,
        "classes_jar_sha256": json.loads((d / "meta.json").read_text())["classes_jar_sha256"],
        "methods": recs,
        "excluded": sorted(excl),
        "summary": {
            "scored_methods": len(recs),
            "excluded": dict(sorted(reasons.items())),
            "classes": len(names),
            "top_level_classes": len({r["top"] for r in recs}),
        },
    }
    tmp = d / f"index.json.gz.new-{os.getpid()}"
    with gzip.open(tmp, "wt") as f:
        json.dump(index, f)
    os.replace(tmp, d / "index.json.gz")
    print(f"[index] {proj.name}: {len(recs)} scored, excluded {dict(reasons)}", file=sys.stderr)
    return index


def load_index(proj: P.Project, rebuild: bool = False, jobs: int = 16) -> dict:
    p = proj.dir / "index.json.gz"
    if p.exists() and not rebuild:
        with gzip.open(p, "rt") as f:
            idx = json.load(f)
        meta = json.loads((proj.dir / "meta.json").read_text())
        if idx.get("version") == INDEX_VERSION and idx.get("classes_jar_sha256") == meta["classes_jar_sha256"]:
            return idx
    return build_index(proj, jobs=jobs)


# --- sampling -----------------------------------------------------------------


def sample_keys(index: dict, size: int, seed: str = "javabench-v1") -> list[str]:
    """Deterministic stratified sample by bytecode size.

    Half the budget is split equally across the five size strata (so large
    methods are represented), the other half proportionally; within a stratum
    methods are taken in order of sha256(seed + key).
    """
    methods = index["methods"]
    if size <= 0 or len(methods) <= size:
        return [m["key"] for m in methods]
    by_s: dict[int, list[str]] = defaultdict(list)
    for m in methods:
        by_s[m["stratum"]].append(m["key"])
    for s in by_s:
        by_s[s].sort(key=lambda k: hashlib.sha256((seed + k).encode()).hexdigest())
    k = len(STRATA)
    quota = {s: 0 for s in range(k)}
    equal = size // 2 // k
    for s in range(k):
        quota[s] = min(equal, len(by_s.get(s, [])))
    remaining = size - sum(quota.values())
    total_left = sum(len(by_s.get(s, [])) - quota[s] for s in range(k))
    for s in range(k):
        left = len(by_s.get(s, [])) - quota[s]
        if total_left:
            quota[s] += min(left, round(remaining * left / total_left))
    # fix rounding drift deterministically
    drift = size - sum(quota.values())
    for s in sorted(range(k), key=lambda s: -len(by_s.get(s, []))):
        if drift == 0:
            break
        room = len(by_s.get(s, [])) - quota[s]
        step = max(-quota[s], min(room, drift))
        quota[s] += step
        drift -= step
    out = []
    for s in range(k):
        out.extend(by_s.get(s, [])[: quota[s]])
    return sorted(out)


def selection(proj: P.Project, index: dict, full: bool) -> tuple[list[str], str]:
    if full or proj.sample_size <= 0:
        return [m["key"] for m in index["methods"]], "full"
    keys = sample_keys(index, proj.sample_size)
    return keys, f"sample{proj.sample_size}"


def subset_jar(proj: P.Project, index: dict, keys: list[str], tag: str) -> Path:
    """Jar with every class of the top-level classes containing ``keys``.

    Also used for ``--full``: classes with no scored method at all (generated
    parsers, Kotlin, package-info) are not handed to the decompilers."""
    out = proj.dir / f"input-{tag}.jar"
    by_key = {m["key"]: m for m in index["methods"]}
    tops = sorted({by_key[k]["top"].replace(".", "/") for k in keys})
    marker = hashlib.sha256(("\n".join(tops) + index["classes_jar_sha256"]).encode()).hexdigest()
    stamp = proj.dir / f"input-{tag}.sha"
    if out.exists() and stamp.exists() and stamp.read_text().strip() == marker:
        return out
    src = zipfile.ZipFile(proj.dir / "classes.jar")
    topset = set(tops)
    tmp = out.with_name(out.name + f".new-{os.getpid()}")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for info in src.infolist():
            n = info.filename
            if not n.endswith(".class"):
                continue
            if n[:-6].split("$")[0] in topset:
                zi = zipfile.ZipInfo(n, date_time=(1980, 1, 1, 0, 0, 0))
                zi.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(zi, src.read(info))
    os.replace(tmp, out)
    stamp.write_text(marker + "\n")
    return out
