#!/usr/bin/env python3
"""Regenerate the stable Rust release-commit table.

Reads the `1.x.y` release tags of rust-lang/rust and writes
`decompiler/crates/kuna-analysis/src/analyzers/sourcelang/kuna_rustreleases.rs`,
sorted by commit hash for binary search.

    python3 scripts/gen_rustreleases.py
"""

import pathlib
import re
import subprocess

REMOTE = "https://github.com/rust-lang/rust"
OUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "decompiler/crates/kuna-analysis/src/analyzers/sourcelang/kuna_rustreleases.rs"
)
TAG = re.compile(r"^([0-9a-f]{40})\trefs/tags/(1\.\d+\.\d+)(\^\{\})?$")


def main() -> None:
    listing = subprocess.run(
        ["git", "ls-remote", "--tags", REMOTE], check=True, capture_output=True, text=True
    ).stdout
    commits: dict[str, str] = {}
    for line in listing.splitlines():
        match = TAG.match(line)
        if match and (match.group(3) or match.group(2) not in commits):
            commits[match.group(2)] = match.group(1)
    rows = sorted((commit, tuple(map(int, tag.split(".")))) for tag, commit in commits.items())
    lines = [
        "//! Stable Rust release commits, sorted by hash.",
        "//! Generated by `scripts/gen_rustreleases.py` from the rust-lang/rust release tags.",
        "",
        "pub(super) const RELEASES: &[(&[u8; 40], (u16, u16, u16))] = &[",
    ]
    lines += [f'    (b"{commit}", ({a}, {b}, {c})),' for commit, (a, b, c) in rows]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
