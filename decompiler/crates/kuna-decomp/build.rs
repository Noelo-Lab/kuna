//! Codegen for the kuna phase registry (ADR 0006).
//!
//! Reads `phases.toml` (the single source of truth for the four static tables
//! transcribed from `decompiler/cpp/kuna_stages.cc`) and generates
//! `$OUT_DIR/phases_generated.rs`, which `kuna_phases.rs` includes. The
//! generated code is:
//!
//!   - the four static tables: `GROUP_TABLE`, `SUBPHASE_TABLE`,
//!     `SURFACE_TABLE`, `SETTABLE_TABLE` (slices of the structs defined in
//!     `kuna_phases.rs`);
//!   - a typed `OptionValues` struct: one field per settable, holding the
//!     option's allowed-value enum, defaulting to the shipped value;
//!   - `OptionValues::default()` (= the `default` column of `settableTable`);
//!   - the `live_value(field, &OptionValues)` lookup that maps a settable
//!     option name to its live value string (the codegen half of
//!     `kuna_console.cc` `kunaLiveValue`).
//!
//! TOML is parsed by a small hand-rolled reader (the file is generated by us
//! and uses only `[[array-of-table]]` headers + `key = "string"` /
//! `key = true|false` lines), so the build stays dependency-free and offline.
//! That parser is intentionally narrow: it rejects anything outside the shape
//! `phases.toml` actually uses, turning a malformed registry into a build
//! error rather than silently-wrong codegen.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// One parsed `[[table]]` row: ordered key -> value, preserving file order.
type Row = Vec<(String, TomlValue)>;

/// A TOML scalar value as used by `phases.toml`.
#[derive(Clone, Debug)]
enum TomlValue {
    Str(String),
    Bool(bool),
}

impl TomlValue {
    fn as_str(&self) -> &str {
        match self {
            TomlValue::Str(s) => s,
            TomlValue::Bool(_) => panic!("phases.toml: expected string, found bool"),
        }
    }
    fn as_bool(&self) -> bool {
        match self {
            TomlValue::Bool(b) => *b,
            TomlValue::Str(_) => panic!("phases.toml: expected bool, found string"),
        }
    }
}

/// Get a required key from a row.
fn req<'a>(row: &'a Row, key: &str) -> &'a TomlValue {
    row.iter()
        .find(|(k, _)| k == key)
        .map(|(_, v)| v)
        .unwrap_or_else(|| panic!("phases.toml: missing required key `{key}` in a row"))
}

/// Get an optional key from a row.
fn opt<'a>(row: &'a Row, key: &str) -> Option<&'a TomlValue> {
    row.iter().find(|(k, _)| k == key).map(|(_, v)| v)
}

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let toml_path = Path::new(&manifest_dir).join("phases.toml");
    println!("cargo:rerun-if-changed=phases.toml");
    println!("cargo:rerun-if-changed=build.rs");

    let text = fs::read_to_string(&toml_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", toml_path.display()));
    let tables = parse_toml(&text);

    let groups = tables.get("group").cloned().unwrap_or_default();
    let substages = tables.get("subphase").cloned().unwrap_or_default();
    let surfaces = tables.get("surface").cloned().unwrap_or_default();
    let settables = tables.get("settable").cloned().unwrap_or_default();

    let mut out = String::new();
    out.push_str("// @generated by build.rs from phases.toml -- DO NOT EDIT.\n\n");

    gen_groups(&mut out, &groups);
    gen_subphases(&mut out, &substages);
    gen_surfaces(&mut out, &surfaces);
    gen_settables(&mut out, &settables);
    gen_option_values(&mut out, &settables);

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");
    let dest = Path::new(&out_dir).join("phases_generated.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));
}

// -----------------------------------------------------------------------------
// Stage / strength enum rendering (the codegen turns "S3" etc. into the variant)
// -----------------------------------------------------------------------------

/// Render a phase code ("P0".."P9" or "infra") as a `KunaPhase` variant path.
fn phase_variant(code: &str) -> String {
    let v = match code {
        "infra" => "Infra",
        "P0" => "P0",
        "P1" => "P1",
        "P2" => "P2",
        "P3" => "P3",
        "P4" => "P4",
        "P5" => "P5",
        "P6" => "P6",
        "P7" => "P7",
        "P8" => "P8",
        "P9" => "P9",
        other => panic!("phases.toml: bad phase code `{other}`"),
    };
    format!("KunaPhase::{v}")
}

/// Render a strength code ("NONE"/"HINT"/"HARD") as a `KunaStrength` variant.
fn strength_variant(code: &str) -> String {
    let v = match code {
        "NONE" => "None",
        "HINT" => "Hint",
        "HARD" => "Hard",
        other => panic!("phases.toml: bad strength code `{other}`"),
    };
    format!("KunaStrength::{v}")
}

/// Escape a string for a Rust string literal.
fn rlit(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

