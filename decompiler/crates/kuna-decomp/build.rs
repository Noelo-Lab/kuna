fn gen_groups(out: &mut String, rows: &[Row]) {
    writeln!(
        out,
        "/// groupTable: every action/rule group name -> its dominant phase."
    )
    .unwrap();
    writeln!(
        out,
        "pub static GROUP_TABLE: [KunaGroupEntry; {}] = [",
        rows.len()
    )
    .unwrap();
    for r in rows {
        writeln!(
            out,
            "    KunaGroupEntry {{ group: {}, phase: {}, subphase: {}, note: {} }},",
            rlit(req(r, "group").as_str()),
            phase_variant(req(r, "phase").as_str()),
            rlit(req(r, "subphase").as_str()),
            rlit(req(r, "note").as_str()),
        )
        .unwrap();
    }
    writeln!(out, "];\n").unwrap();
}

fn gen_subphases(out: &mut String, rows: &[Row]) {
    writeln!(out, "/// subphaseTable: every named decision point.").unwrap();
    writeln!(
        out,
        "pub static SUBPHASE_TABLE: [KunaSubPhase; {}] = [",
        rows.len()
    )
    .unwrap();
    for r in rows {
        writeln!(
            out,
            "    KunaSubPhase {{ name: {}, phase: {}, decision: {}, assertion: {}, strength: {}, rewind: {}, latent: {}, exposure: {} }},",
            rlit(req(r, "name").as_str()),
            phase_variant(req(r, "phase").as_str()),
            rlit(req(r, "decision").as_str()),
            rlit(req(r, "assertion").as_str()),
            strength_variant(req(r, "strength").as_str()),
            phase_variant(req(r, "rewind").as_str()),
            req(r, "latent").as_bool(),
            rlit(req(r, "exposure").as_str()),
        )
        .unwrap();
    }
    writeln!(out, "];\n").unwrap();
}

