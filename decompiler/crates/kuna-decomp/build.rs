/// Turn an option name into a valid Rust field/ident (kebab/option names are
/// already lower_snake-safe here, but normalize defensively).
fn ident(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// Generate the typed `OptionValues` struct + its `Default` + `set`/`get` +
/// `live_value` lookup, mirroring `kunaLiveValue`'s string mapping.
///
/// Each settable becomes a `String` field holding the option's *current* value
/// (one of its pipe-separated `values`), initialized to the shipped `default`.
/// `live_value(option) -> Option<&str>` reproduces `kunaLiveValue`: it returns
/// the live string for the 19 options that have a reader, and `None`
/// (i.e. C++ `""`) for the rest -- so the catalog emitter suppresses the
/// `current` field for exactly the same options as the C++ does.
fn gen_option_values(out: &mut String, rows: &[Row]) {
    writeln!(
        out,
        "/// Typed live option values (ADR 0006): one field per settable, holding the"
    )
    .unwrap();
    writeln!(
        out,
        "/// option's *current* value (one of its allowed `values`); defaults to the"
    )
    .unwrap();
    writeln!(
        out,
        "/// shipped `default`. `live_value` reproduces `kuna_console.cc kunaLiveValue`."
    )
    .unwrap();
    writeln!(out, "#[derive(Clone, Debug, PartialEq, Eq)]").unwrap();
    writeln!(out, "pub struct OptionValues {{").unwrap();
    for r in rows {
        let opt = req(r, "option").as_str();
        writeln!(
            out,
            "    /// Current value of `{}` (allowed: {}).",
            opt,
            req(r, "values").as_str()
        )
        .unwrap();
        writeln!(out, "    pub {}: String,", ident(opt)).unwrap();
    }
    writeln!(out, "}}\n").unwrap();

    // Default
    writeln!(out, "impl Default for OptionValues {{").unwrap();
    writeln!(out, "    fn default() -> Self {{").unwrap();
    writeln!(out, "        OptionValues {{").unwrap();
    for r in rows {
        let opt = req(r, "option").as_str();
        let def = req(r, "default").as_str();
        writeln!(
            out,
            "            {}: {}.to_string(),",
            ident(opt),
            rlit(def)
        )
        .unwrap();
    }
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}\n").unwrap();

    // get / set by option name
    writeln!(out, "impl OptionValues {{").unwrap();
    writeln!(
        out,
        "    /// Get a settable's current value by option name (None if unknown)."
    )
    .unwrap();
    writeln!(out, "    pub fn get(&self, option: &str) -> Option<&str> {{").unwrap();
    writeln!(out, "        match option {{").unwrap();
    for r in rows {
        let opt = req(r, "option").as_str();
        writeln!(
            out,
            "            {} => Some(self.{}.as_str()),",
            rlit(opt),
            ident(opt)
        )
        .unwrap();
    }
    writeln!(out, "            _ => None,").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}\n").unwrap();

    writeln!(
        out,
        "    /// Set a settable's current value by option name; returns false if the"
    )
    .unwrap();
    writeln!(
        out,
        "    /// option is unknown or the value is not one of its allowed `values`."
    )
    .unwrap();
    writeln!(
        out,
        "    pub fn set(&mut self, option: &str, value: &str) -> bool {{"
    )
    .unwrap();
    writeln!(
        out,
        "        let Some(st) = lookup_settable(option) else {{ return false; }};"
    )
    .unwrap();
    writeln!(
        out,
        "        if !st.values.split('|').any(|v| v == value) {{ return false; }}"
    )
    .unwrap();
    writeln!(out, "        match option {{").unwrap();
    for r in rows {
        let opt = req(r, "option").as_str();
        writeln!(
            out,
            "            {} => {{ self.{} = value.to_string(); true }}",
            rlit(opt),
            ident(opt)
        )
        .unwrap();
    }
    writeln!(out, "            _ => false,").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}\n").unwrap();

    // live_value: codegen of kunaLiveValue. Driven by the live_* keys in TOML.
    writeln!(
        out,
        "    /// The live value of a settable (codegen of `kuna_console.cc kunaLiveValue`)."
    )
    .unwrap();
    writeln!(
        out,
        "    ///"
    )
    .unwrap();
    writeln!(
        out,
        "    /// Returns `None` (C++ `\"\"`) for the three options with no live reader"
    )
    .unwrap();
    writeln!(
        out,
        "    /// (loweredswitch/stackguard/namestyle), so the catalog emitter suppresses"
    )
    .unwrap();
    writeln!(
        out,
        "    /// the `current` field for exactly the same options as the C++ does."
    )
    .unwrap();
    writeln!(
        out,
        "    pub fn live_value(&self, option: &str) -> Option<&str> {{"
    )
    .unwrap();
    writeln!(out, "        match option {{").unwrap();
    for r in rows {
        let opt = req(r, "option").as_str();
        if opt_live(r).is_none() {
            continue;
        }
        // The live value IS the stored current value (the OptionValues field
        // holds the live string directly, in the option's own value vocabulary).
        writeln!(
            out,
            "            {} => Some(self.{}.as_str()),",
            rlit(opt),
            ident(opt)
        )
        .unwrap();
    }
    writeln!(out, "            _ => None,").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}\n").unwrap();

    // live_from_arch: maps an Architecture's bool/print flags to the live string,
    // reproducing kunaLiveValue's bool/bool_inv/print kinds. The caller passes a
    // closure that reads the named arch field as a bool (the W4 architecture
    // wiring); this keeps the codegen the single owner of the option<->field map.
    writeln!(
        out,
        "    /// Build the live value of a settable from the architecture-side flag,"
    )
    .unwrap();
    writeln!(
        out,
        "    /// reproducing `kunaLiveValue`'s bool / inverted-bool / print mapping."
    )
    .unwrap();
    writeln!(
        out,
        "    ///"
    )
    .unwrap();
    writeln!(
        out,
        "    /// `read_flag(field)` returns the architecture bool member named `field`"
    )
    .unwrap();
    writeln!(
        out,
        "    /// (e.g. `present_lessequal`); the special `__print_arraynotation` field"
    )
    .unwrap();
    writeln!(
        out,
        "    /// is the `PrintC::getArrayNotation()` flag. Returns `None` for options"
    )
    .unwrap();
    writeln!(
        out,
        "    /// with no live reader (same set as [`OptionValues::live_value`])."
    )
    .unwrap();
    writeln!(
        out,
        "    pub fn live_from_arch<'a>(option: &str, read_flag: impl Fn(&str) -> Option<bool>) -> Option<&'a str> {{"
    )
    .unwrap();
    writeln!(out, "        match option {{").unwrap();
    for r in rows {
        let opt = req(r, "option").as_str();
        let Some((field, true_val, false_val)) = opt_live(r) else {
            continue;
        };
        // C++ kunaLiveValue is a literal `flag ? live_true : live_false` ternary
        // per option (e.g. compareform = present_lessequal ? "original":"canonical");
        // live_true/live_false are stored verbatim, no inversion logic.
        writeln!(
            out,
            "            {} => match read_flag({}) {{ Some(true) => Some({}), Some(false) => Some({}), None => None }},",
            rlit(opt),
            rlit(&field),
            rlit(&true_val),
            rlit(&false_val),
        )
        .unwrap();
    }
    writeln!(out, "            _ => None,").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}\n").unwrap();
}

/// Extract the live mapping (field, value-when-true, value-when-false) from a
/// settable row, if it has a live reader. `live_true`/`live_false` are the
/// literal C++ `kunaLiveValue` ternary branches for the option.
fn opt_live(r: &Row) -> Option<(String, String, String)> {
    let field = opt(r, "live_field")?.as_str().to_string();
    let live_true = req(r, "live_true").as_str().to_string();
    let live_false = req(r, "live_false").as_str().to_string();
    Some((field, live_true, live_false))
}

// -----------------------------------------------------------------------------
// Minimal TOML reader (only the `[[table]]` + `key = "str"|bool` shape we emit)
// -----------------------------------------------------------------------------

/// Parse the (self-generated) `phases.toml` into `table-name -> rows`.
///
/// Supports exactly: blank lines, `#` comments, `[[name]]` array-of-table
/// headers, and `key = value` where `value` is a TOML basic string (`"..."`
/// with `\"`, `\\`, `\n`, `\t`, `\r`, `\uXXXX` escapes) or a bare `true`/`false`.
/// Anything else is a hard error (we control the file's shape).
fn parse_toml(text: &str) -> BTreeMap<String, Vec<Row>> {
    let mut tables: BTreeMap<String, Vec<Row>> = BTreeMap::new();
    let mut cur_table: Option<String> = None;

    for (lineno, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(rest) = line.strip_prefix("[[") {
            let name = rest
                .strip_suffix("]]")
                .unwrap_or_else(|| panic!("phases.toml:{}: bad table header `{line}`", lineno + 1))
                .trim()
                .to_string();
            tables.entry(name.clone()).or_default().push(Row::new());
            cur_table = Some(name);
            continue;
        }
        // key = value
        let eq = line
            .find('=')
            .unwrap_or_else(|| panic!("phases.toml:{}: expected `key = value`, got `{line}`", lineno + 1));
        let key = line[..eq].trim().to_string();
        let valstr = line[eq + 1..].trim();
        let value = parse_value(valstr, lineno + 1);
        let table = cur_table
            .as_ref()
            .unwrap_or_else(|| panic!("phases.toml:{}: key `{key}` outside any [[table]]", lineno + 1));
        tables
            .get_mut(table)
            .expect("table present")
            .last_mut()
            .expect("at least one row")
            .push((key, value));
    }
    tables
}

/// Parse a single TOML scalar value (basic string or bool).
fn parse_value(s: &str, lineno: usize) -> TomlValue {
    if s == "true" {
        return TomlValue::Bool(true);
    }
    if s == "false" {
        return TomlValue::Bool(false);
    }
    let bytes = s.as_bytes();
    if bytes.first() != Some(&b'"') || bytes.last() != Some(&b'"') || s.len() < 2 {
        panic!("phases.toml:{lineno}: unsupported value `{s}` (need a basic string or bool)");
    }
    let inner = &s[1..s.len() - 1];
    let mut out = String::with_capacity(inner.len());
    let mut chars = inner.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some('"') => out.push('"'),
            Some('\\') => out.push('\\'),
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('u') => {
                let hex: String = (0..4).filter_map(|_| chars.next()).collect();
                let code = u32::from_str_radix(&hex, 16)
                    .unwrap_or_else(|_| panic!("phases.toml:{lineno}: bad \\u escape"));
                out.push(char::from_u32(code).unwrap_or('\u{fffd}'));
            }
            other => panic!("phases.toml:{lineno}: bad escape `\\{other:?}`"),
        }
    }
    TomlValue::Str(out)
}
