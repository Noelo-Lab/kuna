//! Generate the phase tables and string-valued option storage from `phases.toml`.

use std::fmt::Write as _;

#[path = "build/registry.rs"]
mod registry;
use registry::{Group, Registry, Settable, Subphase, Surface};

#[cfg(not(test))]
fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let toml_path = std::path::Path::new(&manifest_dir).join("phases.toml");
    println!("cargo:rerun-if-changed=phases.toml");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=build/registry.rs");

    let text = std::fs::read_to_string(&toml_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", toml_path.display()));
    let out = generate(&text).unwrap_or_else(|e| panic!("phases.toml: {e}"));
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let dest = std::path::Path::new(&out_dir).join("phases_generated.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));
}

fn generate(text: &str) -> Result<String, toml::de::Error> {
    let registry: Registry = toml::from_str(text)?;
    let mut out = String::from("// @generated by build.rs from phases.toml -- DO NOT EDIT.\n\n");
    gen_groups(&mut out, &registry.group);
    gen_subphases(&mut out, &registry.subphase);
    gen_surfaces(&mut out, &registry.surface);
    gen_settables(&mut out, &registry.settable);
    gen_option_values(&mut out, &registry.settable);
    Ok(out)
}

/// Render a phase code ("P0".."P9" or "infra") as a `KunaPhase` variant path.
fn phase_variant(code: &str) -> String {
    let v = match code {
        "infra" => "Infra",
        "P0" => "P0",
        "P1" => "P1",
        "P2" => "P2",
        "P3" => "P3",
        "P4" => "P4",
        "P5" => "P5",
        "P6" => "P6",
        "P7" => "P7",
        "P8" => "P8",
        "P9" => "P9",
        other => panic!("phases.toml: bad phase code `{other}`"),
    };
    format!("KunaPhase::{v}")
}

/// Render a strength code ("NONE"/"HINT"/"HARD") as a `KunaStrength` variant.
fn strength_variant(code: &str) -> String {
    let v = match code {
        "NONE" => "None",
        "HINT" => "Hint",
        "HARD" => "Hard",
        other => panic!("phases.toml: bad strength code `{other}`"),
    };
    format!("KunaStrength::{v}")
}

/// Escape a string for a Rust string literal.
fn rlit(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn gen_groups(out: &mut String, rows: &[Group]) {
    writeln!(
        out,
        "/// groupTable: every action/rule group name -> its dominant phase."
    )
    .unwrap();
    writeln!(
        out,
        "pub static GROUP_TABLE: [KunaGroupEntry; {}] = [",
        rows.len()
    )
    .unwrap();
    for r in rows {
        writeln!(
            out,
            "    KunaGroupEntry {{ group: {}, phase: {}, subphase: {}, note: {} }},",
            rlit(r.group.as_str()),
            phase_variant(r.phase.as_str()),
            rlit(r.subphase.as_str()),
            rlit(r.note.as_str()),
        )
        .unwrap();
    }
    writeln!(out, "];\n").unwrap();
}

fn gen_subphases(out: &mut String, rows: &[Subphase]) {
    writeln!(out, "/// subphaseTable: every named decision point.").unwrap();
    writeln!(
        out,
        "pub static SUBPHASE_TABLE: [KunaSubPhase; {}] = [",
        rows.len()
    )
    .unwrap();
    for r in rows {
        writeln!(
            out,
            "    KunaSubPhase {{ name: {}, phase: {}, decision: {}, assertion: {}, strength: {}, rewind: {}, latent: {}, exposure: {} }},",
            rlit(r.name.as_str()),
            phase_variant(r.phase.as_str()),
            rlit(r.decision.as_str()),
            rlit(r.assertion.as_str()),
            strength_variant(r.strength.as_str()),
            phase_variant(r.rewind.as_str()),
            r.latent,
            rlit(r.exposure.as_str()),
        )
        .unwrap();
    }
    writeln!(out, "];\n").unwrap();
}

