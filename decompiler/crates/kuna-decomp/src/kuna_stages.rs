// --- The catalog JSON emitter (byte-compatible with kunaEmitSettableJson) ----

/// Append `str` to `out` as a JSON string literal — byte-for-byte port of
/// `kuna_console.cc kunaJsonString` (quotes + minimal escaping; control chars
/// below 0x20 other than `\n` collapse to a single space).
fn json_string(out: &mut String, s: &str) {
    out.push('"');
    for ch in s.chars() {
        if ch == '"' || ch == '\\' {
            out.push('\\');
            out.push(ch);
        } else if ch == '\n' {
            out.push_str("\\n");
        } else if (ch as u32) < 0x20 {
            // C++ drops other control chars to a single space.
            out.push(' ');
        } else {
            out.push(ch);
        }
    }
    out.push('"');
}

/// Emit one settable as a JSON object onto `out` — byte-for-byte port of
/// `kuna_console.cc kunaEmitSettableJson`.
///
/// `live` is the live current value (C++ joins it from the `Architecture`);
/// pass `None` to suppress the `current` field, exactly as the C++ does when
/// `kunaLiveValue` returns `""` (no program loaded, or no live reader).
pub fn emit_settable_json(out: &mut String, st: &KunaSettable, live: Option<&str>) {
    out.push_str("  {");
    out.push_str("\"option\": ");
    json_string(out, st.option);
    out.push_str(", \"values\": [");
    // Split the pipe-separated values into a JSON array. The C++ walks
    // `pos <= vals.size()` so a trailing empty token (vals ending in '|') would
    // emit an empty "" — replicate that with the inclusive loop below; the
    // catalog never ends a values string in '|', so this matches in practice.
    let vals = st.values;
    let mut first = true;
    let mut pos = 0usize;
    loop {
        let rest = &vals[pos..];
        let (tok, next) = match rest.find('|') {
            Some(bar) => (&rest[..bar], Some(pos + bar + 1)),
            None => (rest, None),
        };
        if !first {
            out.push_str(", ");
        }
        json_string(out, tok);
        first = false;
        match next {
            Some(p) => pos = p,
            None => break,
        }
    }
    out.push(']');
    out.push_str(", \"default\": ");
    json_string(out, st.shipped);
    if let Some(live) = live {
        if !live.is_empty() {
            out.push_str(", \"current\": ");
            json_string(out, live);
        }
    }
    out.push_str(", \"destructive_as_default\": ");
    out.push_str(if st.destructive { "true" } else { "false" });
    out.push_str(", \"stage\": ");
    json_string(out, st.stage.code());
    out.push_str(", \"substage\": ");
    json_string(out, st.substage);
    out.push_str(", \"strength\": ");
    json_string(out, st.strength.catalog_code());
    out.push_str(", \"rewind\": ");
    json_string(out, st.rewind.code());
    out.push_str(", \"issue\": ");
    json_string(out, st.issue);
    out.push_str(", \"summary\": ");
    json_string(out, st.summary);
    out.push_str(", \"use_when\": ");
    json_string(out, st.use_when);
    out.push_str(", \"example\": ");
    json_string(out, st.example);
    out.push_str(", \"source_decompiler\": ");
    json_string(out, st.source_decompiler);
    out.push_str(", \"inspiration\": ");
    json_string(out, st.inspiration);
    out.push_str(", \"change_kind\": ");
    json_string(out, st.change_kind);
    out.push('}');
}

/// Emit the full settable catalog as JSON — byte-for-byte port of
/// `IfcKunaStageCatalog::execute`'s no-argument form (`stage catalog`).
///
/// `live` maps an option name to its live current value (or `None`); pass a
/// closure returning `None` for every option to get the static catalog (the
/// no-program-loaded form, which is what `tests/catalog_bytecompat.rs` pins).
/// The output is the exact bytes the console writes (including the trailing
/// newline after each row and the final `]\n`).
pub fn emit_catalog_json(live: impl Fn(&str) -> Option<&'static str>) -> String {
    let mut out = String::new();
    out.push_str("[\n");
    let n = kuna_num_settables();
    for i in 0..n {
        let st = kuna_settable_by_index(i);
        emit_settable_json(&mut out, st, live(st.option));
        if i + 1 < n {
            out.push(',');
        }
        out.push('\n');
    }
    out.push_str("]\n");
    out
}

/// Emit a single settable's catalog JSON — byte-for-byte port of
/// `IfcKunaStageCatalog::execute`'s one-argument form (`stage catalog <option>`).
///
/// Returns `None` if the option is unknown (the C++ throws an
/// `IfaceExecutionError`); the row is followed by a single newline.
pub fn emit_catalog_json_one(option: &str, live: Option<&str>) -> Option<String> {
    let st = lookup_settable(option)?;
    let mut out = String::new();
    emit_settable_json(&mut out, st, live);
    out.push('\n');
    Some(out)
}

impl fmt::Display for KunaStage {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.code())
    }
}

