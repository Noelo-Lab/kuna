//! Port of `decompiler/cpp/kuna_stages.{cc,hh}` — the kuna stage registry.
//!
//! This is the normative stage model made physical: pure static data + lookups
//! (no pipeline linkage, no output effect). It encodes
//!
//!   - the stages themselves ([`KunaStage`]): the P0 knowledge plane + S1..S9,
//!     with Band B (S3..S6) membership, plus the `Infra` registry-only
//!     pseudo-stage for orchestration units;
//!   - the four static tables transcribed from `kuna_stages.cc`:
//!     [`GROUP_TABLE`] (39 action/rule groups), [`SUBSTAGE_TABLE`] (40 named
//!     decision points), [`SURFACE_TABLE`] (90 console/option surfaces), and
//!     [`SETTABLE_TABLE`] (22 LLM/agent-settable assertions);
//!   - the lookup API (`kuna_num_groups`/`kuna_group_by_index`/`lookup_group`
//!     and siblings — the idiomatic equivalents of the C++ `kunaNumGroups` /
//!     `kunaGroupByIndex` / `kunaLookupGroup` family).
//!
//! Per ADR 0006 the four tables and the typed [`OptionValues`] struct are
//! **generated by `build.rs` from `stages.toml`** (the single source of truth):
//! the generated code is `include!`d below. The catalog JSON emitter
//! ([`emit_settable_json`]) is hand-written to be byte-compatible with
//! `kuna_console.cc kunaEmitSettableJson` (ADR 0006); `tests/catalog_bytecompat.rs`
//! string-matches it against the C++ binary's captured output.

use core::fmt;

/// (kuna) The stages of the kuna stage model (`docs/stages.md`).
///
/// `Infra` is the registry-only pseudo-stage for orchestration units
/// (ActionStart/Stop, the cleanup pool's termination policy) that own no model
/// artifact — the C++ `kstage_infra = -1`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum KunaStage {
    /// Orchestration / termination policy (no artifact) — C++ `kstage_infra`.
    Infra,
    /// Knowledge & Configuration Plane (orthogonal) — C++ `kstage_p0`.
    P0,
    /// Image & Code Partition — C++ `kstage_s1`.
    S1,
    /// Flow & Op-Graph Recovery — C++ `kstage_s2`.
    S2,
    /// Definition Web (Band B) — C++ `kstage_s3`.
    S3,
    /// Call & Prototype Model (Band B) — C++ `kstage_s4`.
    S4,
    /// Value & Type Facts (Band B) — C++ `kstage_s5`.
    S5,
    /// Variable & Storage Model (Band B) — C++ `kstage_s6`.
    S6,
    /// Region Hierarchy — C++ `kstage_s7`.
    S7,
    /// Structured AST & Goto Quality — C++ `kstage_s8`.
    S8,
    /// Surface Rendering & Refinement — C++ `kstage_s9`.
    S9,
}

impl KunaStage {
    /// The numeric value of the stage matching the C++ `enum KunaStage` (infra
    /// is -1, P0 is 0, S1..S9 are 1..9).
    pub fn index(self) -> i32 {
        match self {
            KunaStage::Infra => -1,
            KunaStage::P0 => 0,
            KunaStage::S1 => 1,
            KunaStage::S2 => 2,
            KunaStage::S3 => 3,
            KunaStage::S4 => 4,
            KunaStage::S5 => 5,
            KunaStage::S6 => 6,
            KunaStage::S7 => 7,
            KunaStage::S8 => 8,
            KunaStage::S9 => 9,
        }
    }

    /// "P0".."S9" (or "--" for infra) — C++ `kunaStageCode`.
    pub fn code(self) -> &'static str {
        STAGE_CODES[self.code_index()]
    }

    /// Long stage name — C++ `kunaStageName`.
    pub fn name(self) -> &'static str {
        STAGE_NAMES[self.code_index()]
    }

    /// The artifact the stage owns — C++ `kunaStageArtifact`.
    pub fn artifact(self) -> &'static str {
        STAGE_ARTIFACTS[self.code_index()]
    }

    /// true for S3..S6 — C++ `kunaStageInBandB`.
    pub fn in_band_b(self) -> bool {
        // C++: (stage >= kstage_s3 && stage <= kstage_s6); the enum ordering of
        // S3..S6 mirrors the numeric one (infra=-1 sorts below P0).
        let i = self.index();
        (KunaStage::S3.index()..=KunaStage::S6.index()).contains(&i)
    }

    /// Index into the `STAGE_*` arrays: 0..=9 for P0..S9, 10 for infra.
    fn code_index(self) -> usize {
        match self {
            KunaStage::Infra => 10,
            other => other.index() as usize,
        }
    }

    /// Parse "P0"/"s3"/... into the stage — C++ `kunaStageFromCode`.
    ///
    /// Returns `None` on a malformed code (the C++ returns `false` and leaves
    /// `res` unset).
    pub fn from_code(code: &str) -> Option<KunaStage> {
        if code.len() != 2 {
            return None;
        }
        let bytes = code.as_bytes();
        let c0 = bytes[0];
        let c1 = bytes[1];
        if (c0 == b'p' || c0 == b'P') && c1 == b'0' {
            return Some(KunaStage::P0);
        }
        if (c0 == b's' || c0 == b'S') && (b'1'..=b'9').contains(&c1) {
            // C++: res = (KunaStage)(c1 - '0'); S1..S9 are 1..9.
            return Some(match c1 - b'0' {
                1 => KunaStage::S1,
                2 => KunaStage::S2,
                3 => KunaStage::S3,
                4 => KunaStage::S4,
                5 => KunaStage::S5,
                6 => KunaStage::S6,
                7 => KunaStage::S7,
                8 => KunaStage::S8,
                9 => KunaStage::S9,
                _ => unreachable!("c1 guaranteed in 1..=9"),
            });
        }
        None
    }
}

/// (kuna) Assertion strength (`stage-model.md` section 2) — C++ `KunaStrength`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum KunaStrength {
    /// No assertion exists (fully LATENT decision) — C++ `kstrength_none`.
    None,
    /// Biases inference — C++ `kstrength_hint`.
    Hint,
    /// Blocks inference unconditionally — C++ `kstrength_hard`.
    Hard,
}

impl KunaStrength {
    /// "HARD"/"HINT"/"NONE" — the catalog rendering of a strength.
    pub fn catalog_code(self) -> &'static str {
        match self {
            KunaStrength::Hard => "HARD",
            KunaStrength::Hint => "HINT",
            KunaStrength::None => "NONE",
        }
    }
}

/// (kuna) One action/rule group mapped to its dominant stage — C++ `KunaGroupEntry`.
#[derive(Clone, Copy, Debug)]
pub struct KunaGroupEntry {
    /// Group name as used in `coreaction.cc`.
    pub group: &'static str,
    /// Dominant stage (straddlers: by owned artifact, section 15).
    pub stage: KunaStage,
    /// Sub-stage operated, or "" if stage-wide.
    pub substage: &'static str,
    /// Straddler / secondary-effect note, or "".
    pub note: &'static str,
}

/// (kuna) One sub-stage: a named decision point inside a stage — C++ `KunaSubStage`.
#[derive(Clone, Copy, Debug)]
pub struct KunaSubStage {
    /// Short kebab-case name (stable identifier).
    pub name: &'static str,
    /// Owning stage.
    pub stage: KunaStage,
    /// What is being decided.
    pub decision: &'static str,
    /// The P0 assertion type that overrides it.
    pub assertion: &'static str,
    /// Strength of that assertion.
    pub strength: KunaStrength,
    /// Minimal invalidated stage (section 12); Ghidra-actual is whole-function.
    pub rewind: KunaStage,
    /// true = no override surface exists in kuna today.
    pub latent: bool,
    /// Surface that operates it ("option ...", "command ...", or roadmap note).
    pub exposure: &'static str,
}

/// (kuna) One existing console/option surface routed to a sub-stage — C++ `KunaSurfaceEntry`.
#[derive(Clone, Copy, Debug)]
pub struct KunaSurfaceEntry {
    /// "option <name>" or the console command words.
    pub surface: &'static str,
    /// Stage it operates.
    pub stage: KunaStage,
    /// Sub-stage name (in the catalog), or "".
    pub substage: &'static str,
    /// Clarification, or "".
    pub note: &'static str,
}

/// (kuna) One LLM/agent-settable assertion: the machine-readable catalog row —
/// C++ `KunaSettable`.
#[derive(Clone, Copy, Debug)]
pub struct KunaSettable {
    /// The option name (the `option <name> ...` token).
    pub option: &'static str,
    /// Pipe-separated legal values, e.g. "on|off" or "canonical|original".
    pub values: &'static str,
    /// The value kuna ships as the default (post-DIV-2 where applicable).
    pub shipped: &'static str,
    /// true = NOT safe as a global default (kept opt-in).
    pub destructive: bool,
    /// Owning stage.
    pub stage: KunaStage,
    /// Sub-stage name (in the §4-§10 catalog).
    pub substage: &'static str,
    /// Assertion strength.
    pub strength: KunaStrength,
    /// Minimal invalidated stage (REPORTED; Ghidra-actual is whole-function).
    pub rewind: KunaStage,
    /// Originating issue (e.g. "GH-558"), or "".
    pub issue: &'static str,
    /// One line: the decision this assertion controls.
    pub summary: &'static str,
    /// Symptom -> when an operator should flip it away from the default.
    pub use_when: &'static str,
    /// A ready-to-use console command, e.g. "option compareform canonical".
    pub example: &'static str,
    /// (kuna) Which decompiler the behavior was observed/ported from.
    pub source_decompiler: &'static str,
    /// (kuna) Concrete origin pointer (upstream issue/PR, or reference class).
    pub inspiration: &'static str,
    /// (kuna) Gates default-on eligibility.
    pub change_kind: &'static str,
}

