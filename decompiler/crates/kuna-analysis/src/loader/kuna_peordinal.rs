//! (kuna) `peordinal` — name a PE import-by-ordinal from a built-in export table.
//!
//! A PE may import a function by ordinal only, with no name in its Import Name
//! Table. `pe_iat` then synthesizes `<DLL>_Ordinal_<n>`, which carries no
//! meaning for a reader and matches no signature table. For a handful of system
//! DLLs whose ordinals are fixed by their `.def` files and that toolchains
//! routinely import by ordinal, the ordinal-to-name mapping is public and
//! stable, so it is compiled in here and consulted first.
//!
//! The tables are the consensus of independent export listings (the Windows
//! exports as recorded by RetDec's and radare2's ordinal databases, Wine's
//! built DLLs, and pefile's `ordlookup`): an ordinal is admitted only when every
//! listing that has it agrees on the name. `WS2_32` is further restricted to the
//! WinSock 1.1 ordinals (1-23, 51-57, 101-116, 151, 500), the only ones that are
//! stable across Windows releases. `WSOCK32` is its own table: it swaps
//! `inet_addr`/`inet_ntoa`/`ioctlsocket` relative to `WS2_32`.
//!
//! Gated by [`kuna_decomp::kuna_peordinal`] (default on); off restores the
//! synthesized `<DLL>_Ordinal_<n>` names.

/// The built-in name for `dll!ordinal`, when `dll` is a covered system DLL.
pub(crate) fn ordinal_name(dll: &[u8], ord: u16) -> Option<&'static str> {
    let table = table_for(dll)?;
    table
        .binary_search_by_key(&ord, |&(o, _)| o)
        .ok()
        .map(|i| table[i].1)
}

/// The table for a DLL name, matched case-insensitively with or without `.dll`.
fn table_for(dll: &[u8]) -> Option<&'static [(u16, &'static str)]> {
    let dll = String::from_utf8_lossy(dll).to_ascii_lowercase();
    let stem = dll.strip_suffix(".dll").unwrap_or(&dll);
    match stem {
        "oleaut32" => Some(OLEAUT32),
        "ws2_32" => Some(WS2_32),
        "wsock32" => Some(WSOCK32),
        "msvbvm60" => Some(MSVBVM60),
        _ => None,
    }
}

