use kuna_base::marshal::{AttributeId, ElementId};

macro_rules! define_ids {
    ($kind:ident, $table:ident; $($constant:ident = ($name:literal, $value:literal)),* $(,)?) => {
        $(pub const $constant: $kind = $kind::new($name, $value);)*
        pub(super) const $table: &[$kind] = &[$($constant),*];
    };
}

