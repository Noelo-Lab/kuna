import java.lang.reflect.Method;
import java.net.URI;
import java.nio.file.FileSystems;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Stream;

/**
 * Generates kuna-jvm's table of the JDK methods for which Vineflower's
 * ClasspathHelper.findMethod (reflection on the JVM running the decompiler) can answer a varargs
 * method: Method.toString() of every varargs method in getMethods() of every class of this JVM's
 * runtime image that `new ClassLoader(null) {}` loads (the bootstrap loader), restricted to
 * methods declared by that class (toString names the declaring class, so an inherited method
 * never contains the queried signature) whose return and parameter types are all references
 * (a signature spells a primitive as its descriptor letter, so it never matches one).
 * Run as a class-path application, the way Vineflower runs, so the boot layer is the same.
 * See gen.sh.
 */
public class JdkVarargs {
  public static void main(String[] args) throws Exception {
    List<String> names = new ArrayList<>();
    try (Stream<Path> walk = Files.walk(FileSystems.getFileSystem(URI.create("jrt:/")).getPath("/modules"))) {
      walk.filter(p -> p.getNameCount() > 2 && p.toString().endsWith(".class")).forEach(p -> {
        String rel = p.subpath(2, p.getNameCount()).toString();
        names.add(rel.substring(0, rel.length() - ".class".length()).replace('/', '.'));
      });
    }

    int loaded = 0;
    List<String> lines = new ArrayList<>();
    for (String name : names) {
      Class<?> cls;
      try {
        cls = new ClassLoader(null) {}.loadClass(name);
      }
      catch (Exception e) {
        continue;
      }
      loaded++;
      for (Method m : cls.getMethods()) {
        if (m.isVarArgs() && m.getDeclaringClass() == cls && isReference(m.getReturnType())
            && Stream.of(m.getParameterTypes()).allMatch(JdkVarargs::isReference)) {
          lines.add(m.toString());
        }
      }
    }
    lines.sort(Comparator.comparing(JdkVarargs::member).thenComparing(Comparator.naturalOrder()));

    System.out.println("# kuna-jvm ClasspathHelper JDK facts, generated by tests/data/jdk_varargs/gen.sh; do not edit");
    System.out.println("# " + System.getProperty("java.vm.name") + " " + System.getProperty("java.runtime.version")
                       + ": " + names.size() + " classes, " + loaded + " on the bootstrap loader, " + lines.size() + " methods");
    lines.forEach(System.out::println);
  }

  private static String member(String method) {
    return method.substring(method.lastIndexOf(' ', method.indexOf('(')) + 1);
  }

  private static boolean isReference(Class<?> type) {
    while (type.isArray()) {
      type = type.getComponentType();
    }
    return !type.isPrimitive();
  }
}
