#!/usr/bin/env python3
"""Write hash-pinnable shadow copies of Vineflower 1.12.0's identity-hashed classes.

Each listed source is copied from the Vineflower checkout (verified against its 1.12.0 sha256)
with two members inserted after the class's opening line: a creation index taken from the
class's kuna arena counter, and hashCode() delegating to kuna.vftrace.HashMode.

usage: gen_shadow.py VF_SRC OUT_DIR
"""
import hashlib
import os
import sys

SOURCES = [
    ("modules/decompiler/stats/Statement.java", 0,
     "c865cb216474a39ef36c7a32d9ffcd97c2bc2b8ccc02c5a8cd786349a3353d89"),
    ("modules/decompiler/StatEdge.java", 1,
     "960fbf5501958f0f010fd6be71c96e1b10c5555a812a9019dee14647f7242956"),
    ("modules/decompiler/exps/Exprent.java", 2,
     "33798ac25a0310a443085aa5e26ed5fa4f2c1365092e998deeb70f5c1dad8513"),
    ("code/cfg/BasicBlock.java", 3,
     "e4c65d1eb4cff097b137cb2b9e1aafc8c74af271924d02b45935b8a3039a1626"),
    ("code/Instruction.java", 4,
     "70d6ce63201494c34db94c51239321a505c5e897cd46e285609f521023ef569b"),
    ("code/cfg/ExceptionRangeCFG.java", 5,
     "faf1f43b4abb563028120d68385470e70fb8b21108133810314fc4e7e7e91832"),
    ("modules/decompiler/vars/VarVersionNode.java", 6,
     "458c065f8cedd11afcab6274bc357a22fd33fb832a13fa0097bb9711ea8fda04"),
]

PREFIX = "src/org/jetbrains/java/decompiler"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    vf_src, out_dir = sys.argv[1], sys.argv[2]
    for rel, arena, sha in SOURCES:
        path = os.path.join(vf_src, PREFIX, rel)
        with open(path, "rb") as f:
            data = f.read()
        got = hashlib.sha256(data).hexdigest()
        if got != sha:
            sys.exit(f"{path}: sha256 {got} is not the Vineflower 1.12.0 source")
        name = os.path.basename(rel)[:-5]
        lines = data.decode("utf-8").split("\n")
        for i, line in enumerate(lines):
            if line.startswith("public ") and f" class {name}" in line and line.rstrip().endswith("{"):
                break
        else:
            sys.exit(f"{path}: class declaration of {name} not found")
        lines.insert(i + 1, (
            f"  private final int vftraceIndex = kuna.vftrace.HashMode.next({arena});\n"
            f"  @Override public int hashCode() {{ return kuna.vftrace.HashMode.hash({arena}, vftraceIndex, this); }}"
        ))
        dest = os.path.join(out_dir, "org/jetbrains/java/decompiler", rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8") as f:
            f.write("// Generated by kuna-jvm tools/vftrace/gen_shadow.py from Vineflower 1.12.0; do not edit.\n")
            f.write("\n".join(lines))


if __name__ == "__main__":
    main()
