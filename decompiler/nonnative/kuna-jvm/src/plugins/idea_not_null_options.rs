//! Port of `org/vineflower/ideanotnull/IdeaNotNullOptions.java`. The annotated
//! option field Vineflower reads by reflection is the table `OPTIONS`.

use crate::i_fernflower_preferences::{OptionType, PreferenceOption};
use crate::plugin_options::AddDefaults;

pub struct IdeaNotNullOptions;

impl IdeaNotNullOptions {
    pub const IDEA_NOT_NULL_ANNOTATION: &'static str = "resugar-idea-notnull";

    /// The option fields, in declaration order.
    pub const OPTIONS: &'static [PreferenceOption] = &[PreferenceOption {
        field: "IDEA_NOT_NULL_ANNOTATION",
        key: IdeaNotNullOptions::IDEA_NOT_NULL_ANNOTATION,
        short_name: Some("inn"),
        name: Some("Resugar Intellij IDEA @NotNull"),
        description: Some("Resugar Intellij IDEA's code generated by @NotNull annotations."),
        type_: Some(OptionType::Boolean),
        dynamic_default_value: None,
    }];

    pub fn add_defaults(cons: &mut dyn AddDefaults) {
        cons.add_default(IdeaNotNullOptions::IDEA_NOT_NULL_ANNOTATION, "1");
    }
}
