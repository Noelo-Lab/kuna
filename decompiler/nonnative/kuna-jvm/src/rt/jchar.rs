//! `java.lang.Character` classification for UTF-16 units (Java `char`).
//!
//! Every predicate is derived from the JDK 21 general category of the unit
//! (`Character.getType`), held in [`TYPE_RUNS`] for all of 0..=0xFFFF, using
//! the JDK's own definitions; `tests/data/GenJcharGolden.java` regenerates the
//! table and checks every predicate against the JVM for every `char`.
//! Supplementary code points are not covered: Vineflower only classifies `char`s.

pub const UNASSIGNED: i32 = 0;
pub const UPPERCASE_LETTER: i32 = 1;
pub const LOWERCASE_LETTER: i32 = 2;
pub const TITLECASE_LETTER: i32 = 3;
pub const MODIFIER_LETTER: i32 = 4;
pub const OTHER_LETTER: i32 = 5;
pub const NON_SPACING_MARK: i32 = 6;
pub const ENCLOSING_MARK: i32 = 7;
pub const COMBINING_SPACING_MARK: i32 = 8;
pub const DECIMAL_DIGIT_NUMBER: i32 = 9;
pub const LETTER_NUMBER: i32 = 10;
pub const OTHER_NUMBER: i32 = 11;
pub const SPACE_SEPARATOR: i32 = 12;
pub const LINE_SEPARATOR: i32 = 13;
pub const PARAGRAPH_SEPARATOR: i32 = 14;
pub const CONTROL: i32 = 15;
pub const FORMAT: i32 = 16;
pub const PRIVATE_USE: i32 = 18;
pub const SURROGATE: i32 = 19;
pub const DASH_PUNCTUATION: i32 = 20;
pub const START_PUNCTUATION: i32 = 21;
pub const END_PUNCTUATION: i32 = 22;
pub const CONNECTOR_PUNCTUATION: i32 = 23;
pub const OTHER_PUNCTUATION: i32 = 24;
pub const MATH_SYMBOL: i32 = 25;
pub const CURRENCY_SYMBOL: i32 = 26;
pub const MODIFIER_SYMBOL: i32 = 27;
pub const INITIAL_QUOTE_PUNCTUATION: i32 = 29;
pub const FINAL_QUOTE_PUNCTUATION: i32 = 30;

pub const MIN_RADIX: i32 = 2;
pub const MAX_RADIX: i32 = 36;

fn run_index(ch: u16) -> usize {
    TYPE_RUNS.partition_point(|&(start, _)| start <= ch) - 1
}

/// `Character.getType(char)`.
pub fn get_type(ch: u16) -> i32 {
    TYPE_RUNS[run_index(ch)].1 as i32
}

/// `Character.isLetter(char)`.
pub fn is_letter(ch: u16) -> bool {
    (UPPERCASE_LETTER..=OTHER_LETTER).contains(&get_type(ch))
}

/// `Character.isDigit(char)`.
pub fn is_digit(ch: u16) -> bool {
    get_type(ch) == DECIMAL_DIGIT_NUMBER
}

/// `Character.isLetterOrDigit(char)`.
pub fn is_letter_or_digit(ch: u16) -> bool {
    let t = get_type(ch);
    (UPPERCASE_LETTER..=OTHER_LETTER).contains(&t) || t == DECIMAL_DIGIT_NUMBER
}

/// `Character.isIdentifierIgnorable(char)`.
pub fn is_identifier_ignorable(ch: u16) -> bool {
    matches!(ch, 0x00..=0x08 | 0x0E..=0x1B | 0x7F..=0x9F) || get_type(ch) == FORMAT
}

/// `Character.isJavaIdentifierStart(char)`.
pub fn is_java_identifier_start(ch: u16) -> bool {
    if ch < 0x80 {
        let b = ch as u8;
        return b.is_ascii_alphabetic() || b == b'$' || b == b'_';
    }
    let t = get_type(ch);
    (UPPERCASE_LETTER..=OTHER_LETTER).contains(&t)
        || t == LETTER_NUMBER
        || t == CURRENCY_SYMBOL
        || t == CONNECTOR_PUNCTUATION
}

/// `Character.isJavaIdentifierPart(char)`.
pub fn is_java_identifier_part(ch: u16) -> bool {
    if ch < 0x80 {
        let b = ch as u8;
        return b.is_ascii_alphanumeric() || b == b'$' || b == b'_' || is_identifier_ignorable(ch);
    }
    let t = get_type(ch);
    (UPPERCASE_LETTER..=OTHER_LETTER).contains(&t)
        || matches!(
            t,
            LETTER_NUMBER
                | CURRENCY_SYMBOL
                | CONNECTOR_PUNCTUATION
                | DECIMAL_DIGIT_NUMBER
                | COMBINING_SPACING_MARK
                | NON_SPACING_MARK
        )
        || is_identifier_ignorable(ch)
}

/// `Character.isWhitespace(char)`.
pub fn is_whitespace(ch: u16) -> bool {
    if matches!(ch, 0x09..=0x0D | 0x1C..=0x1F) {
        return true;
    }
    if matches!(ch, 0x00A0 | 0x2007 | 0x202F) {
        return false;
    }
    matches!(
        get_type(ch),
        SPACE_SEPARATOR | LINE_SEPARATOR | PARAGRAPH_SEPARATOR
    )
}

/// `Character.isISOControl(char)`.
pub fn is_iso_control(ch: u16) -> bool {
    matches!(ch, 0x00..=0x1F | 0x7F..=0x9F)
}

/// `Character.isSurrogate(char)`.
pub fn is_surrogate(ch: u16) -> bool {
    (0xD800..=0xDFFF).contains(&ch)
}

/// `Character.isHighSurrogate(char)`.
pub fn is_high_surrogate(ch: u16) -> bool {
    (0xD800..=0xDBFF).contains(&ch)
}

/// `Character.isLowSurrogate(char)`.
pub fn is_low_surrogate(ch: u16) -> bool {
    (0xDC00..=0xDFFF).contains(&ch)
}

/// `Character.digit(char, radix)`: -1 when `ch` is not a digit of `radix`.
pub fn digit(ch: u16, radix: i32) -> i32 {
    if !(MIN_RADIX..=MAX_RADIX).contains(&radix) {
        return -1;
    }
    let value = match ch {
        0x30..=0x39 => (ch - 0x30) as i32,
        0x41..=0x5A => (ch - 0x41) as i32 + 10,
        0x61..=0x7A => (ch - 0x61) as i32 + 10,
        0xFF21..=0xFF3A => (ch - 0xFF21) as i32 + 10,
        0xFF41..=0xFF5A => (ch - 0xFF41) as i32 + 10,
        _ if ch < 0x80 => -1,
        _ => {
            let (start, kind) = TYPE_RUNS[run_index(ch)];
            if kind as i32 == DECIMAL_DIGIT_NUMBER {
                ((ch - start) % 10) as i32
            } else {
                -1
            }
        }
    };
    if value < radix {
        value
    } else {
        -1
    }
}

