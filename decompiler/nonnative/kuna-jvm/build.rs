//! Generates the JVM option table (`kuna_options`) from `options.toml`.

use std::fmt::Write as _;

use serde::Deserialize;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Table {
    option: Vec<Row>,
    driver_owned: Vec<DriverOwned>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Row {
    option: String,
    vineflower: String,
    short: String,
    aliases: Vec<String>,
    values: String,
    default: String,
    destructive: bool,
    phase: String,
    subphase: String,
    strength: String,
    rewind: String,
    issue: String,
    summary: String,
    use_when: String,
    example: String,
    source_decompiler: String,
    inspiration: String,
    change_kind: String,
    tier: String,
    symptoms: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct DriverOwned {
    vineflower: String,
    kuna: String,
}

fn main() {
    println!("cargo:rerun-if-changed=options.toml");
    println!("cargo:rerun-if-changed=build.rs");
    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let path = std::path::Path::new(&dir).join("options.toml");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let table: Table = toml::from_str(&text).unwrap_or_else(|e| panic!("options.toml: {e}"));
    for row in &table.option {
        check(row).unwrap_or_else(|e| panic!("options.toml: {}: {e}", row.option));
    }
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let dest = std::path::Path::new(&out_dir).join("jvm_options.rs");
    std::fs::write(&dest, generate(&table))
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));
}

fn check(row: &Row) -> Result<(), String> {
    let required = [
        ("values", &row.values),
        ("phase", &row.phase),
        ("subphase", &row.subphase),
        ("rewind", &row.rewind),
        ("summary", &row.summary),
        ("use_when", &row.use_when),
        ("example", &row.example),
        ("source_decompiler", &row.source_decompiler),
        ("inspiration", &row.inspiration),
        ("change_kind", &row.change_kind),
        ("symptoms", &row.symptoms),
    ];
    for (field, value) in required {
        if value.trim().is_empty() {
            return Err(format!("`{field}` is empty"));
        }
    }
    if !row.option.starts_with("jvm_") {
        return Err("the name must start with jvm_".to_string());
    }
    if row.strength != "HARD" {
        return Err("`strength` must be HARD".to_string());
    }
    if !["core", "transform", "analysis"].contains(&row.tier.as_str()) {
        return Err(format!("unknown tier {}", row.tier));
    }
    if !row.example.starts_with("kuna ") || !row.example.contains(&row.option) {
        return Err("`example` must be a kuna command using the option".to_string());
    }
    if row.symptoms.split('|').any(|s| s.trim().is_empty()) {
        return Err("empty symptom".to_string());
    }
    let mut expected: Vec<&str> = Vec::new();
    if !row.vineflower.is_empty() {
        expected.push(&row.vineflower);
        if row.option != format!("jvm_{}", row.vineflower.replace('-', "_")) {
            return Err(format!("the name must be jvm_ + {}", row.vineflower));
        }
    }
    if !row.short.is_empty() {
        expected.push(&row.short);
    }
    if row.aliases != expected {
        return Err(format!("`aliases` must be {expected:?}"));
    }
    Ok(())
}

fn generate(table: &Table) -> String {
    let mut out = String::from("// @generated by build.rs from options.toml -- DO NOT EDIT.\n\n");
    out.push_str("/// Every row of `options.toml`, in file order.\npub static JVM_OPTION_TABLE: &[JvmOption] = &[\n");
    for r in &table.option {
        let aliases: Vec<String> = r.aliases.iter().map(|a| format!("{a:?}")).collect();
        let _ = writeln!(
            out,
            "    JvmOption {{ option: {:?}, vineflower: {:?}, short: {:?}, aliases: &[{}], values: {:?}, default: {:?}, destructive: {}, phase: {:?}, subphase: {:?}, strength: {:?}, rewind: {:?}, issue: {:?}, summary: {:?}, use_when: {:?}, example: {:?}, source_decompiler: {:?}, inspiration: {:?}, change_kind: {:?}, tier: {:?}, symptoms: {:?} }},",
            r.option,
            r.vineflower,
            r.short,
            aliases.join(", "),
            r.values,
            r.default,
            r.destructive,
            r.phase,
            r.subphase,
            r.strength,
            r.rewind,
            r.issue,
            r.summary,
            r.use_when,
            r.example,
            r.source_decompiler,
            r.inspiration,
            r.change_kind,
            r.tier,
            r.symptoms,
        );
    }
    out.push_str("];\n\n/// The Vineflower keys kuna sets itself, with what sets them.\npub static JVM_DRIVER_OWNED: &[DriverOwned] = &[\n");
    for d in &table.driver_owned {
        let _ = writeln!(
            out,
            "    DriverOwned {{ vineflower: {:?}, kuna: {:?} }},",
            d.vineflower, d.kuna
        );
    }
    out.push_str("];\n");
    out
}
