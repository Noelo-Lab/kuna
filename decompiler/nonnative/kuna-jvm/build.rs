//! Generates the JVM option table (`kuna_options`) from `options.toml`, and
//! the fix registry (`KunaFix` of `kuna_fixes`) from `fixes.toml`.

use std::fmt::Write as _;

use serde::Deserialize;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Table {
    option: Vec<Row>,
    driver_owned: Vec<DriverOwned>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Row {
    option: String,
    vineflower: String,
    short: String,
    aliases: Vec<String>,
    values: String,
    default: String,
    destructive: bool,
    phase: String,
    subphase: String,
    strength: String,
    rewind: String,
    issue: String,
    summary: String,
    use_when: String,
    example: String,
    source_decompiler: String,
    inspiration: String,
    change_kind: String,
    tier: String,
    symptoms: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct DriverOwned {
    vineflower: String,
    kuna: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Fixes {
    fix: Vec<Fix>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Fix {
    id: String,
    family: String,
    #[serde(default)]
    kotlin: bool,
}

fn main() {
    println!("cargo:rerun-if-changed=options.toml");
    println!("cargo:rerun-if-changed=fixes.toml");
    println!("cargo:rerun-if-changed=build.rs");
    let table: Table = parse("options.toml");
    for row in &table.option {
        check(row).unwrap_or_else(|e| panic!("options.toml: {}: {e}", row.option));
    }
    write("jvm_options.rs", generate(&table));
    let fixes: Fixes = parse("fixes.toml");
    write("jvm_fixes.rs", generate_fixes(&fixes.fix));
}

fn parse<T: serde::de::DeserializeOwned>(name: &str) -> T {
    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let path = std::path::Path::new(&dir).join(name);
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    toml::from_str(&text).unwrap_or_else(|e| panic!("{name}: {e}"))
}

fn write(name: &str, text: String) {
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let dest = std::path::Path::new(&out_dir).join(name);
    std::fs::write(&dest, text).unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));
}

fn check(row: &Row) -> Result<(), String> {
    let required = [
        ("values", &row.values),
        ("phase", &row.phase),
        ("subphase", &row.subphase),
        ("rewind", &row.rewind),
        ("summary", &row.summary),
        ("use_when", &row.use_when),
        ("example", &row.example),
        ("source_decompiler", &row.source_decompiler),
        ("inspiration", &row.inspiration),
        ("change_kind", &row.change_kind),
        ("symptoms", &row.symptoms),
    ];
    for (field, value) in required {
        if value.trim().is_empty() {
            return Err(format!("`{field}` is empty"));
        }
    }
    if !row.option.starts_with("jvm_") {
        return Err("the name must start with jvm_".to_string());
    }
    if row.strength != "HARD" {
        return Err("`strength` must be HARD".to_string());
    }
    if !["core", "transform", "analysis"].contains(&row.tier.as_str()) {
        return Err(format!("unknown tier {}", row.tier));
    }
    if !row.example.starts_with("kuna ") || !row.example.contains(&row.option) {
        return Err("`example` must be a kuna command using the option".to_string());
    }
    if row.symptoms.split('|').any(|s| s.trim().is_empty()) {
        return Err("empty symptom".to_string());
    }
    let mut expected: Vec<&str> = Vec::new();
    if !row.vineflower.is_empty() {
        expected.push(&row.vineflower);
        if row.option != format!("jvm_{}", row.vineflower.replace('-', "_")) {
            return Err(format!("the name must be jvm_ + {}", row.vineflower));
        }
    }
    if !row.short.is_empty() {
        expected.push(&row.short);
    }
    if row.aliases != expected {
        return Err(format!("`aliases` must be {expected:?}"));
    }
    Ok(())
}

fn generate(table: &Table) -> String {
    let mut out = String::from("// @generated by build.rs from options.toml -- DO NOT EDIT.\n\n");
    out.push_str("/// Every row of `options.toml`, in file order.\npub static JVM_OPTION_TABLE: &[JvmOption] = &[\n");
    for r in &table.option {
        let aliases: Vec<String> = r.aliases.iter().map(|a| format!("{a:?}")).collect();
        let _ = writeln!(
            out,
            "    JvmOption {{ vineflower: {:?}, short: {:?}, row: OptionRow {{ option: {:?}, aliases: &[{}], values: {:?}, default: {:?}, destructive: {}, phase: {:?}, subphase: {:?}, strength: {:?}, rewind: {:?}, issue: {:?}, summary: {:?}, use_when: {:?}, example: {:?}, source_decompiler: {:?}, inspiration: {:?}, change_kind: {:?}, tier: {:?}, symptoms: {:?} }} }},",
            r.vineflower,
            r.short,
            r.option,
            aliases.join(", "),
            r.values,
            r.default,
            r.destructive,
            r.phase,
            r.subphase,
            r.strength,
            r.rewind,
            r.issue,
            r.summary,
            r.use_when,
            r.example,
            r.source_decompiler,
            r.inspiration,
            r.change_kind,
            r.tier,
            r.symptoms,
        );
    }
    out.push_str("];\n\n/// The Vineflower keys kuna sets itself, with what sets them.\npub static JVM_DRIVER_OWNED: &[DriverOwned] = &[\n");
    for d in &table.driver_owned {
        let _ = writeln!(
            out,
            "    DriverOwned {{ vineflower: {:?}, kuna: {:?} }},",
            d.vineflower, d.kuna
        );
    }
    out.push_str("];\n");
    out
}

/// `KunaFix`, one variant per row (its id in CamelCase), with `ALL` in row
/// order, `id` and `kotlin`. Each id must be lower snake case, and each
/// family's rows must be together.
fn generate_fixes(fixes: &[Fix]) -> String {
    let mut families: Vec<&str> = Vec::new();
    for f in fixes {
        let snake = f.id.split('_').all(|w| {
            w.starts_with(|c: char| c.is_ascii_lowercase())
                && w.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
        });
        assert!(snake, "fixes.toml: {}: the id must be lower snake case", f.id);
        if families.last() != Some(&f.family.as_str()) {
            assert!(
                !families.contains(&f.family.as_str()),
                "fixes.toml: {}: the rows of family {} must be together",
                f.id,
                f.family
            );
            families.push(&f.family);
        }
    }
    let variant = |f: &Fix| -> String {
        f.id.split('_').map(|w| w[..1].to_ascii_uppercase() + &w[1..]).collect()
    };
    let lines = |line: &dyn Fn(&Fix) -> String| fixes.iter().map(line).collect::<String>();
    let kotlin: Vec<String> = fixes
        .iter()
        .filter(|f| f.kotlin)
        .map(|f| format!("KunaFix::{}", variant(f)))
        .collect();
    format!(
        "// @generated by build.rs from fixes.toml -- DO NOT EDIT.

/// One kuna-only fix, a row of `fixes.toml`; its id is [`KunaFix::id`].
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum KunaFix {{
{variants}}}

impl KunaFix {{
    /// Every fix, in `fixes.toml` order.
    pub const ALL: &'static [KunaFix] = &[
{all}    ];

    /// The fix's id, as the docs and `tests/jvm/kuna-fixes/cases.json` name it.
    pub fn id(self) -> &'static str {{
        match self {{
{ids}        }}
    }}

    /// Whether the fix changes only Kotlin output (`kotlin = true`).
    pub fn kotlin(self) -> bool {{
        matches!(self, {kotlin})
    }}
}}
",
        variants = lines(&|f| format!("    {},\n", variant(f))),
        all = lines(&|f| format!("        KunaFix::{},\n", variant(f))),
        ids = lines(&|f| format!("            KunaFix::{} => {:?},\n", variant(f), f.id)),
        kotlin = kotlin.join(" | "),
    )
}
