def with_aux(body):
    """Follow a constructor's own writes of CC0..CC3 with the CCA/CCB update."""
    last = None
    for m in re.finditer(r"CC[0-3] = [^;]*;", body):
        last = m
    return body if last is None else body[:last.end()] + " ccAux();" + body[last.end():]
def C(disp, pat, body, act=""):
    I(f":{disp} is {pat}{(' ' + act) if act else ''} {{ {with_aux(body)} }}")

class F:
    def __init__(s, tok, r1=None, r2=None, r3=None, mem=None):
        s.tok, s.r1n, s.r2n, s.r3n, s.mem = tok, r1, r2, r3, mem
    def reg(s, nib, kind=""):
        return f"{s.tok}_r{kind}{nib}"
    def r1(s, k=""): return s.reg(s.r1n, k)
    def r2(s, k=""): return s.reg(s.r2n, k)
    def r3(s, k=""): return s.reg(s.r3n, k)
def pat(fmt, opc):
    if fmt == "RR": return f"a_op8=0x{opc:02x}"
    if fmt in ("RRE", "RRF"): return f"b_op16=0x{opc:04x}"
    if fmt in ("RX", "RS", "SI"): return f"b_op8=0x{opc:02x}"
    if fmt == "RI": return f"b_op8=0x{opc >> 4:02x} & b_op4=0x{opc & 15:x}"
    if fmt == "RIL": return f"c_op8=0x{opc >> 4:02x} & c_op4=0x{opc & 15:x}"
    if fmt in ("RXY", "RSY", "RIE", "SIY", "RXE"): return f"c_op8=0x{opc >> 8:02x} & c_opl=0x{opc & 255:02x}"
    if fmt in ("SIL",): return f"c_op16=0x{opc:04x}"
    if fmt == "SS": return f"c_op8=0x{opc:02x}"
    raise KeyError(fmt)
