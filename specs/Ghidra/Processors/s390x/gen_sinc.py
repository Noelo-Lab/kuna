def rng(f, lo, hi):
    """Constraint `lo <= f <= hi` over a 4-bit field; None if it cannot hold, [] if it always does."""
    lo, hi = max(lo, 0), min(hi, 15)
    if lo > hi: return None
    out = []
    if lo == hi: return [f"{f}={lo}"]
    if lo > 0: out.append(f"{f}>={lo}")
    if hi < 15: out.append(f"{f}<={hi}")
    return out
def conj(*parts):
    acc = []
    for p in parts:
        if p is None: return None
        acc += p if isinstance(p, list) else [p]
    return " & ".join(acc)
def member(k, a, b):
    return (a <= k <= b) if a <= b else (k >= a or k <= b)
def runs(vals):
    out = []
    for v in vals:
        if out and out[-1][1] == v - 1: out[-1][1] = v
        else: out.append([v, v])
    return out
def predicate(t, k, want):
    A, B = f"{t}_nA", f"{t}_nB"
    terms = []
    for a in range(16):
        bs = [b for b in range(16) if member(k, a, b) == want]
        for lo, hi in runs(bs):
            terms.append("(" + " & ".join([f"{A}={a}"] + rng(B, lo, hi)) + ")")
    return " | ".join(terms)
