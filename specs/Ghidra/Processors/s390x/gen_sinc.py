def source(fmt, w, src):
    """(display, pattern, expression of width w) for the second operand."""
    f = FM[fmt]
    if src == "r": n = f.r2(KS[w]); return n, n, n
    if src == "rs32": n = f.r2("l"); return n, n, f"sext({n})"
    if src == "rz32": n = f.r2("l"); return n, n, f"zext({n})"
    if src == "rs16": n = f.r2("l"); return n, n, f"sext({n}:2)"
    if src == "rs8": n = f.r2("l"); return n, n, f"sext({n}:1)"
    if src == "rz16": n = f.r2("l"); return n, n, f"zext({n}:2)"
    if src == "rz8": n = f.r2("l"); return n, n, f"zext({n}:1)"
    if src[0] == "m":
        n, ext = int(src[1:-1]) if src[-1] in "sz" else int(src[1:]), src[-1]
        e = f"*:{n} {f.mem}"
        if n < w: e = ("sext" if ext == "s" else "zext") + f"({e})"
        return f.mem, f.mem, e
    if src[:3] == "rel":
        n, ext = int(src[3:-1]) if src[-1] in "sz" else int(src[3:]), src[-1]
        e = f"*:{n} RELA32"
        if n < w: e = ("sext" if ext == "s" else "zext") + f"({e})"
        return "RELA32", "RELA32", e
    imm = {"RI": {"i16s": "b_si16", "i16z": "b_i16"}, "RIL": {"i32s": "c_si32", "i32z": "c_i32"},
           "RIE": {"i16s": "c_si16"}}[fmt][src]
    return imm, imm, imm

def body(op, w, a, b, dst):
    pre = f"local x:{w} = {a}; local y:{w} = {b}; "
    if op == "add":  return pre + f"local res:{w} = x + y; ccAddS(x, y, res); {dst} = res;"
    if op == "sub":  return pre + f"local res:{w} = x - y; ccSubS(x, y, res); {dst} = res;"
    if op == "addl": return pre + f"local cy:1 = carry(x, y); local res:{w} = x + y; ccCarry(cy, res); {dst} = res;"
    if op == "subl": return pre + f"local cy:1 = (x >= y); local res:{w} = x - y; ccCarry(cy, res); {dst} = res;"
    if op == "alc":  return pre + f"local ci:{w} = zext(CCA); local t:{w} = x + y; local cy:1 = carry(x, y) || carry(t, ci); local res:{w} = t + ci; ccCarry(cy, res); {dst} = res;"
    if op == "slb":  return pre + f"local bi:{w} = zext(!CCA); local t:{w} = x - y; local cy:1 = (x >= y) && (t >= bi); local res:{w} = t - bi; ccCarry(cy, res); {dst} = res;"
    if op in ("and", "or", "xor"):
        o = {"and": "&", "or": "|", "xor": "^"}[op]
        return pre + f"local res:{w} = x {o} y; ccLogic(res); {dst} = res;"
    if op == "cmp":  return pre + "ccCmpS(x, y);"
    if op == "cmpl": return pre + "ccCmpU(x, y);"
    if op == "ld":   return f"{dst} = {b};"
    if op == "lt":   return f"local res:{w} = {b}; ccSigned(res); {dst} = res;"
    if op == "mul":  return f"{dst} = {a} * {b};"
    if op == "lc":   return f"local y:{w} = {b}; local res:{w} = -y; CC3 = sborrow(0:{w}, y); CC0 = (res == 0); CC1 = (res s< 0) && !CC3; CC2 = (res s> 0) && !CC3; {dst} = res;"
    if op == "lp":   return f"local y:{w} = {b}; local sg:{w} = y s>> {w * 8 - 1}; local res:{w} = (y ^ sg) - sg; CC0 = (res == 0); CC1 = 0; CC2 = (res s> 0); CC3 = (res s< 0); {dst} = res;"
    if op == "ln":   return f"local y:{w} = {b}; local sg:{w} = y s>> {w * 8 - 1}; local res:{w} = sg - (y ^ sg); CC0 = (res == 0); CC1 = (res s< 0); CC2 = 0; CC3 = 0; {dst} = res;"
    raise KeyError(op)

def arith(mn, fmt, opc, w, op, src):
    f = FM[fmt]
    sd, sp, se = source(fmt, w, src)
    dst = f.r1(KS[w])
    if fmt == "RRF":        # three-operand: R1 = R2 op R3
        a = f.r2(KS[w]); b = f.r3(KS[w])
        C(f"{mn} {dst},{a},{b}", f"{pat(fmt, opc)} & {dst} & {a} & {b}", body(op, w, a, b, dst))
    elif fmt == "RIE":      # R1 = R3 op imm
        a = f.r3(KS[w])
        C(f"{mn} {dst},{a},{sd}", f"{pat(fmt, opc)} & {dst} & {a} & {sp}", body(op, w, a, se, dst))
    else:
        C(f"{mn} {dst},{sd}", f"{pat(fmt, opc)} & {dst} & {sp}", body(op, w, dst, se, dst))

