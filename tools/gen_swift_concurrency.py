#!/usr/bin/env python3
"""Generate the Swift concurrency runtime prototype table.

Source: `include/swift/Runtime/Concurrency.h` of the Swift project
(https://github.com/swiftlang/swift, Apache-2.0 with Runtime Library
Exception), at the tag named by `TAG`. Every `SWIFT_EXPORT_FROM(swift_Concurrency)
SWIFT_CC(...)` function declaration becomes one row of
`decompiler/crates/kuna-analysis/src/analyzers/swift/kuna_swiftconcurrency.rs`:
its name, its return and parameter types reduced to the handful the
decompiler spells, the parameter names the header gives, and the position
of the `SWIFT_ASYNC_CONTEXT` parameter when it has one.

    tools/gen_swift_concurrency.py            # fetch the header at TAG
    tools/gen_swift_concurrency.py Concurrency.h   # or read a local copy
    tools/gen_swift_concurrency.py --check    # fail when the table is stale
"""

import re
import sys
import urllib.request
from pathlib import Path

TAG = "swift-6.2-RELEASE"
URL = f"https://raw.githubusercontent.com/swiftlang/swift/{TAG}/include/swift/Runtime/Concurrency.h"
OUT = Path(__file__).resolve().parent.parent / "decompiler/crates/kuna-analysis/src/analyzers/swift/kuna_swiftconcurrency.rs"

DECL = re.compile(r"SWIFT_EXPORT_FROM\(swift_Concurrency\)\s+SWIFT_CC\((\w+)\)\s*([^;{]+?)\s*;", re.S)

WORDS = {
    "size_t", "uintptr_t", "uint64_t", "unsigned long long", "JobPriority", "JobDelay",
    "AsyncContinuationFlags", "swift_task_is_current_executor_flag",
}
EXECUTORS = {"SerialExecutorRef", "TaskExecutorRef"}


def reduce_type(text):
    """The table's spelling of a C++ type, or None for one it has no word for."""
    t = re.sub(r"/\*.*?\*/", " ", text)
    t = " ".join(t.replace("const ", " ").split())
    if "(" in t or "::" in t:
        return "Ptr"
    if t.endswith("*"):
        base = t.rstrip("* ").strip()
        if t.count("*") == 1:
            if base == "Metadata":
                return "Meta"
            if base == "AsyncContext":
                return "Ctx"
            if base == "ContinuationAsyncContext":
                return "ContCtx"
            if base in ("char", "unsigned char"):
                return "Str"
        return "Ptr"
    if t == "void":
        return "Void"
    if t == "bool":
        return "Bool"
    if t in WORDS:
        return "Size"
    if t == "long long":
        return "Int"
    if t in ("int", "swift_clock_id"):
        return "U32"
    if t in EXECUTORS:
        return "Exec"
    if t == "AsyncTaskAndContext":
        return "TaskAndContext"
    return None


def split_params(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out]


def parse(header):
    rows, skipped = [], []
    for cc, decl in DECL.findall(header):
        decl = " ".join(decl.replace("[[noreturn]]", " ").split())
        m = re.match(r"(.*?)\b(swift_\w+)\s*\((.*)\)$", decl)
        if not m or "(*" in m.group(1):
            continue
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
        ret_t = reduce_type(ret)
        plist, context, ok = [], None, ret_t is not None
        for p in [] if params in ("", "void") else split_params(params):
            if "SWIFT_ASYNC_CONTEXT" in p:
                context = len(plist)
                p = p.replace("SWIFT_ASYNC_CONTEXT", " ").strip()
            p = re.sub(r"/\*.*?\*/", " ", p).strip()
            fn = re.match(r".*\(\s*\*\s*(\w+)\s*\)\s*\(.*\)$", p)
            if fn:
                ty, pname = "Ptr", fn.group(1)
            else:
                nm = re.match(r"(.*?[\s*&])(\w+)$", p)
                if nm and reduce_type(nm.group(1)) is not None and reduce_type(p) is None:
                    ty, pname = reduce_type(nm.group(1)), nm.group(2)
                elif nm and nm.group(1).strip().endswith("*") and not p.endswith("*"):
                    ty, pname = reduce_type(nm.group(1)), nm.group(2)
                else:
                    ty, pname = reduce_type(p), ""
            if ty is None or ty in ("Void", "TaskAndContext"):
                ok = False
                break
            plist.append((ty, pname))
        if not ok or (context is not None and cc != "swiftasync"):
            skipped.append(name)
            continue
        if all(name != r[0] for r in rows):
            rows.append((name, ret_t, plist, context))
    rows.sort()
    return rows, skipped


def render(rows, skipped):
    lines = [
        "//! (kuna `swiftcall`) The Swift concurrency runtime's entry points.",
        "//!",
        f"//! GENERATED by `tools/gen_swift_concurrency.py` from",
        f"//! `include/swift/Runtime/Concurrency.h` of the Swift project at `{TAG}`",
        "//! (Apache-2.0 with Runtime Library Exception). Do not edit: change the",
        "//! generator and run it again.",
        "//!",
        "//! One row per exported function: its return type, its parameters with the",
        "//! names the header gives them, and the position of the parameter that",
        "//! rides in the `swiftasync` register, for the entry points that take the",
        "//! caller's context there.",
    ]
    if skipped:
        lines.append("//!")
        lines.append("//! Left to recovery (a type the table has no word for): " + ", ".join(f"`{s}`" for s in sorted(skipped)) + ".")
    lines += [
        "",
        "use super::kuna_swiftruntime::Ty::{self, *};",
        "",
        "pub struct Entry {",
        "    pub name: &'static str,",
        "    pub ret: Ty,",
        "    pub params: &'static [(Ty, &'static str)],",
        "    /// The parameter passed in the `swiftasync` register.",
        "    pub context: Option<usize>,",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub const CONCURRENCY: &[Entry] = &[",
    ]
    for name, ret, plist, context in rows:
        params = ", ".join(f'({t}, "{n}")' for t, n in plist)
        ctx = "None" if context is None else f"Some({context})"
        lines.append(f'    Entry {{ name: "{name}", ret: {ret}, params: &[{params}], context: {ctx} }},')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv):
    check = "--check" in argv
    paths = [a for a in argv if not a.startswith("--")]
    if paths:
        header = Path(paths[0]).read_text()
    else:
        with urllib.request.urlopen(URL) as r:
            header = r.read().decode()
    text = render(*parse(header))
    if check:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run tools/gen_swift_concurrency.py")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main(sys.argv[1:])
